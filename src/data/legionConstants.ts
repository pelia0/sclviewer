export function getSchoolColor(school?: number): string {
  if (!school) return "#e5cc80";
  if (SPELL_SCHOOL_COLORS[school]) return SPELL_SCHOOL_COLORS[school];
  if (school & 4) return SPELL_SCHOOL_COLORS[4];
  if (school & 16) return SPELL_SCHOOL_COLORS[16];
  if (school & 32) return SPELL_SCHOOL_COLORS[32];
  if (school & 8) return SPELL_SCHOOL_COLORS[8];
  if (school & 2) return SPELL_SCHOOL_COLORS[2];
  if (school & 64) return SPELL_SCHOOL_COLORS[64];
  return "#60a5fa";
}

