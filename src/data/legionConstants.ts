export function getWowheadIconUrl(icon: string, size: "small" | "medium" | "large" = "medium"): string {
  const clean = (icon || "inv_misc_questionmark").replace(/\.jpg$/i, "").toLowerCase();
  return `https://wow.zamimg.com/images/wow/icons/${size}/${encodeURIComponent(clean)}.jpg`;
}

export function formatDurationMs(ms: number): string {
  const totalSec = Math.max(0, ms / 1000);
  const m = Math.floor(totalSec / 60);
  const s = Math.floor(totalSec % 60);
  return `${m}:${String(s).padStart(2, "0")}`;
}

export function formatTimestampMMSS(ms: number, withMillis = false): string {
  const safe = Math.max(0, ms);
  const totalSec = safe / 1000;
  const m = Math.floor(totalSec / 60);
  const sec = totalSec % 60;
  if (withMillis) {
    return `${String(m).padStart(2, "0")}:${sec.toFixed(3).padStart(6, "0")}`;
  }
  return `${String(m).padStart(2, "0")}:${sec.toFixed(1).padStart(4, "0")}`;
}

export function formatNumberCompact(num: number): string {
  const abs = Math.abs(num);
  if (abs >= 1_000_000_000) return `${(num / 1_000_000_000).toFixed(2)}B`;
  if (abs >= 1_000_000) return `${(num / 1_000_000).toFixed(2)}M`;
  if (abs >= 1_000) return `${(num / 1_000).toFixed(1)}K`;
  return Math.round(num).toLocaleString();
}

export function getKeyMedalStars(durationMs: number, dungeonId: number): number {
  const meta = DUNGEON_BY_ID[dungeonId];
  if (!meta) return 1;
  if (durationMs <= meta.timerMs * 0.6) return 3;
  if (durationMs <= meta.timerMs * 0.8) return 2;
  if (durationMs <= meta.timerMs) return 1;
  return 0;
}
